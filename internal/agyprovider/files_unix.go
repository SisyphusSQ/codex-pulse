//go:build !windows

package agyprovider

import (
	"os"
	"path/filepath"
)

func pinSourceDatabase(path string) (func(), error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, ErrCollector
	}
	return func() {}, nil
}

func openRegularFileReadOnly(path string) (*os.File, os.FileInfo, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, nil, ErrCollector
	}
	file, err := os.Open(path)
	if err != nil {
		return nil, nil, err
	}
	opened, err := file.Stat()
	if err != nil || !os.SameFile(info, opened) || !opened.Mode().IsRegular() {
		_ = file.Close()
		return nil, nil, ErrCollector
	}
	return file, opened, nil
}

func readDirSafe(path string) ([]os.DirEntry, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return nil, ErrCollector
	}
	return os.ReadDir(filepath.Clean(path))
}
